#[inline]
pub(super) fn is_compound_operator_unicode(first: char, second: char) -> bool {
    matches!(
        (first, second),
        ('+' | '-' | '*' | '/' | '%' | '&' | '|' | '^' | '.' | '<' | '>' | '=' | '!', '=')
            | ('=' | '!' | '~', '~')
            | ('+', '+')
            | ('-', '-' | '>')
            | ('&', '&')
            | ('|', '|')
            | ('<', '<')
            | ('>' | '=', '>')
            | ('*', '*')
            | ('/', '/')
            | ('.', '.')
            | (':', ':')
    )
}
