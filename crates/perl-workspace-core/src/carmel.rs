    #[test]
    fn parses_escaped_and_empty_artifact_entries() {
        // Perl single-quote escapes: `\\` is one backslash, `\'` is one quote
        // (Data::Dumper emits exactly these inside single-quoted strings).
        let source = concat!(
            "our %environment = (\n",
            "  'inc' => [\n",
            "    'C:\\\\repo\\\\blib\\\\arch',\n",
            "    'it\\'s/blib/lib'\n",
            "  ],\n",
            "  'base' => '',\n",
            ");\n",
            "1;\n"
        );
        let facts = parse_mysetup_environment(source).expect("parses");
        assert_eq!(
            facts.inc.as_deref(),
            Some(&["C:\\repo\\blib\\arch".to_string(), "it's/blib/lib".to_string()][..])
        );
        assert_eq!(facts.base.as_deref(), Some(""));
    }

