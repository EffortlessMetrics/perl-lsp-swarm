-- World A: leaf_one patches json.lua; leaf_two patches util.lua (disjoint).
local function disjoint_world()
  local base_dir, base_dig = make_base("f1")
  local s1 = "return { name = 'json-after-one' }\n"
  local s2 = "return { name = 'util-after-two' }\n"
  local c1 = comp("leaf_one", "aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa",
    { "json.lua" }, { ["json.lua"] = s1 }, {})
  local c2 = comp("leaf_two", "bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb",
    { "util.lua" }, { ["util.lua"] = s2 }, {})
  local m = manifest({ c1, c2 },
    { prof("p", { "leaf_one", "leaf_two" }) }, base_dig)
  local ad = fake_adapter({ commits = {
    [c1.candidate_sha] = { paths = { ["json.lua"] = s1 } },
    [c2.candidate_sha] = { paths = { ["util.lua"] = s2 } },
  } })
  return base_dir, m, ad, c1, c2, s1, s2
end

-- F1: non-overlapping patches compose.
do
  local base_dir, m, ad, c1, c2, s1, s2 = disjoint_world()
  local res, tree_dir = run(m, ad, "p", "f1", base_dir)
  ok(type(res) == "table" and res.tree_digest ~= nil, "F1 composes with a tree digest")
  ok(read_file(tree_dir .. "/json.lua") == s1, "F1 json.lua carries leaf_one bytes")
  ok(read_file(tree_dir .. "/util.lua") == s2, "F1 util.lua carries leaf_two bytes")
  ok(res.inventory["json.lua"] == fnv_hex(s1), "F1 inventory records json blob")
  ok(res.receipt_json:find('"leaf_one"', 1, true) ~= nil,
    "F1 receipt lists leaf_one")
  ok(res.receipt_json:find('"leaf_two"', 1, true) ~= nil,
    "F1 receipt lists leaf_two")
  ok(res.receipt_json:find("timestamp", 1, true) == nil
    and res.receipt_json:find("built_at", 1, true) == nil,
    "F1 receipt excludes wall-clock inputs")
end

-- F2: ordered dependent overlapping patches compose; later winner owns.
do
  local base_dir = make_base("f2")
