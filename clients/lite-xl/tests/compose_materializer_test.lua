local scratch_root = (os.getenv("TEMP") or ".") .. "/compose_materializer_scratch"
local IS_WINDOWS = package.config:sub(1, 1) == "\\"
os.execute(IS_WINDOWS
  and ('mkdir "' .. scratch_root .. '" 2>nul')
  or ('mkdir -p "' .. scratch_root .. '" 2>/dev/null'))

-- Directory creation is deferred and flushed as ONE chained command:
-- process spawns dominate runtime on this host.
local CREATED = { [scratch_root] = true }
local PENDING = {}

local function sandbox(name)
  local dir = scratch_root .. "/" .. name
  if not CREATED[dir] then
    CREATED[dir] = true
    PENDING[#PENDING + 1] = dir
  end
  return dir
end

local function flush_dirs()
  if #PENDING == 0 then return end
  local parts = {}
  for _, d in ipairs(PENDING) do
    parts[#parts + 1] = IS_WINDOWS
      and ('mkdir "' .. d .. '" 2>nul')
      or ('mkdir -p "' .. d .. '" 2>/dev/null')
  end
  PENDING = {}
  os.execute(table.concat(parts, IS_WINDOWS and " & " or " && "))
end

local function write_file(path, bytes)
  local dir = path:match("^(.*)[/\\]")
  if dir and not CREATED[dir] then
    sandbox(dir:sub(#scratch_root + 2))
  end
  flush_dirs()
  local f = io.open(path, "wb")
  f:write(bytes)
  f:close()
end

local BASE_BYTES = {
  ["json.lua"] = "return { name = 'pristine-json' }\n",
  ["util.lua"] = "return { name = 'pristine-util' }\n",
}

-- Build a sandbox with pristine base modules; returns base_dir and the
-- matching base digest map.
local function make_base(name)
  local base_dir = sandbox(name)
  local digests = {}
  for p, bytes in pairs(BASE_BYTES) do
    write_file(base_dir .. "/" .. p, bytes)
    digests[p] = fnv_hex(bytes)
  end
  return base_dir, digests
end

local function comp(id, sha, paths, snap_bytes, prereqs, class)
  local content = {}
  for _, p in ipairs(paths) do
    content[p] = fnv_hex(snap_bytes[p])
  end
  local conflict_keys = {}
  for _, p in ipairs(paths) do
    conflict_keys[#conflict_keys + 1] = "lite-xl.upstream." .. p
  end
  return {
    id = id,
    issue = 1,
    candidate_sha = sha,
    changed_paths = paths,
    hard_prerequisites = prereqs or {},
    class = class or "protocol",
    upstream_state = "internal",
    owner_issue = 1,
    conflict_keys = conflict_keys,
    invalidation_inputs = { "candidate_sha", "upstream_base_ref" },
    content = content,
  }
end

local function prof(id, members, admitted)
  return {
    id = id,
    claim = "fixture envelope",
    admitted_classes = admitted or { protocol = true },
    members = members,
  }
end

local function manifest(components, profiles, base_files)
  return {
    schema = "candidate-manifest.v1",
    upstream_base = { repository = "fixture/x", ref = "fix000", files = base_files },
    components = components,
    profiles = profiles,
  }
end

local function load_compose()
  local okk, mod = pcall(dofile, compose_path)
  ok(okk, "compose module loads (" .. tostring(mod) .. ")")
  return okk and mod or nil
end

local compose = load_compose()
if not compose then
  print(string.format("compose_materializer_test: %d passed, %d failed", passed, failed))
  os.exit(1)
end

-- Explicit-call variant keeping base_dir under test control.
local function run(m, adapter, profile_id, tag, base_dir)
  local tree_dir = sandbox(tag .. "_tree")
  local receipt_path = sandbox(tag .. "_rcpt") .. "/receipt.json"
  local res = compose.materialize({
    manifest = m,
    adapter = adapter,
    profile = profile_id,
    base_dir = base_dir,
    out_dir = tree_dir,
    receipt_path = receipt_path,
  })
  return res, tree_dir, receipt_path
end

local function read_file(path)
  local f = io.open(path, "rb")
  if not f then return nil end
  local b = f:read("*a")
  f:close()
  return b
end

