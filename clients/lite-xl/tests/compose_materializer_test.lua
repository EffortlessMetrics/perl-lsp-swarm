-- Deterministic fixture tests for the #11170 deterministic composition
-- materializer.
--
-- Run:
--   lua clients/lite-xl/tests/compose_materializer_test.lua [path-to-compose]
-- Default module path is ../compose.lua relative to this file.
--
-- Seam owned: the MATERIALIZER LAWS over a hermetic fake source adapter -
-- no real git, no real staged tree, fully controlled snapshots. Each issue
-- scenario is one fixture:
--
--   F1  two non-overlapping patches compose;
--   F2  ordered dependent overlapping patches compose (declared edge,
--       later declared winner owns the path);
--   F3  an UNDECLARED overlap stops with typed undeclared_overlap naming
--       both components and the shared path (combined-tree interaction);
--   F4  a wrong base digest stops with typed base_digest_mismatch;
--   F5  snapshot bytes drifting from the recorded reviewed digest stop
--       with typed digest_mismatch (the no-fuzz/skipped-hunk analog:
--       whole-file snapshots cannot fuzz, so any divergence from the
--       reviewed bytes is fatal);
--   F6  a member whose hard prerequisite is absent from the profile stops
--       with typed missing_prerequisite;
--   F7  a stale internal candidate SHA stops with typed stale_candidate_sha;
--   F8  an extra hand-edited file in the generated tree fails verify with
--       typed unowned_diff;
--   F9  the same members declared in a different listed order produce a
--       byte-identical tree digest and receipt (order derives only from
--       dependencies);
--   F10 regeneration is byte-identical and second-run clean;
--   F11 a quality-class component inserted into a core-class-only profile
--       stops with typed class_violation;
--   F12 NEGATIVE CONTROL: flipping one generated byte after composition
--       changes the tree digest and fails verification;
--   F13 a dependency cycle stops with typed dependency_cycle;
--   F14 a component introducing a NEW file (not in the base) materializes
--       additively;
--   F15 an empty profile materializes the pristine base tree exactly.
--
-- Receipts carry no wall-clock input anywhere ("timestamp"/"built_at"
-- never appear); determinism comes from inputs alone.
--
-- Red-first baseline: run against CURRENT MAIN before this patch - there
-- is no compose.lua yet, so loading this suite fails (nonzero exit).
--
-- Mutation falsifiers of the PATCHED module (each mechanically verified
-- against a mutated copy; 11-mutant battery all red):
--   1. skip the prereq-closure membership check -> F6 observes silent
--     materialization instead of missing_prerequisite;
--   2. let the last writer win without checking declared dependencies ->
--     F3 observes silent path stealing instead of undeclared_overlap;
--   3. digest laws are enforced at TWO layers (snapshot verification AND
--     write-back inventory comparison); removing either single layer keeps
--     F5 red via the survivor - only removing BOTH lets drifted bytes
--     compose green (verified);
--   4. verify_tree has two unowned-diff branches (extra file, mutated
--     bytes); disabling one still catches F8/F12 via the other; disabling
--     verification entirely is caught (verified);
--   5. take application order from listed order instead of deriving it
--     from dependencies -> F9 observes order-dependent output and F2
--     observes wrong chain winners (verified);
--   6. stamp os.time into the receipt -> F10 observes nondeterministic
--     receipts (verified).

local compose_path = arg and arg[1] or nil
if not compose_path then
  local info = debug.getinfo(1, "S").source:sub(2)
  local dir = info:match("^(.*)[/\\]") or "."
  compose_path = dir .. "/../compose.lua"
end

local passed, failed = 0, 0
local function ok(condition, message)
  if condition then
    passed = passed + 1
  else
    failed = failed + 1
    print("FAIL: " .. message)
  end
end

local function expect_error(code, fn, label)
  local ran, err = pcall(fn)
  if ran then
    ok(false, label .. ": expected typed error " .. code .. ", none raised")
    return nil
  end
  if type(err) ~= "table" or err.compose_error ~= true then
    ok(false, label .. ": raised non-typed error: " .. tostring(err))
    return nil
  end
  ok(err.code == code,
    label .. ": typed " .. code .. " (got " .. tostring(err.code) .. ")")
  return err
end

-- ---------------------------------------------------------------------------
-- Deterministic content hashing for the hermetic sandbox (FNV-1a 32-bit).
-- ---------------------------------------------------------------------------

local function fnv_hex(bytes)
  local h = 2166136261
  local b = { string.byte(bytes, 1, #bytes) }
  for i = 1, #b do
    h = h ~ b[i]
    h = (h * 16777619) & 0xFFFFFFFF
  end
  return string.format("%08x", h)
end

-- ---------------------------------------------------------------------------
-- Hermetic fake adapter
-- ---------------------------------------------------------------------------

local function fake_adapter(spec)
  local commits = spec.commits or {}
  local ancestors = spec.ancestors or {}
  return {
    component_exists = function(sha)
      return commits[sha] ~= nil and commits[sha].exists ~= false
    end,
    touched_upstream_paths = function(sha)
      local c = commits[sha]
      local out = {}
      if c and c.paths then
        for p in pairs(c.paths) do out[#out + 1] = p end
      end
      table.sort(out)
      return out
    end,
    snapshot = function(sha, path, dest)
      local c = commits[sha]
      local bytes = c and c.paths and c.paths[path] or nil
      if not bytes then
        error("fixture has no snapshot " .. sha .. ":" .. path)
      end
      local f = io.open(dest, "wb")
      f:write(bytes)
      f:close()
      return true
    end,
    is_ancestor = function(a, b)
      return ancestors[a .. ">" .. b] == true
    end,
    hash_file = function(path)
      local f = io.open(path, "rb")
      if not f then error("no file " .. path) end
      local bytes = f:read("*a")
      f:close()
      return fnv_hex(bytes)
    end,
    digest_text = function(text)
      return fnv_hex(text)
    end,
  }
end

