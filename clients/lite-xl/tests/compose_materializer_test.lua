  local s2 = "return { v = 1, extra = true }\n"
  local c1 = comp("dep_first", "1111111111111111111111111111111111111111",
    { "json.lua" }, { ["json.lua"] = s1 }, {})
  local c2 = comp("dep_second", "2222222222222222222222222222222222222222",
    { "json.lua" }, { ["json.lua"] = s2 }, { "dep_first" })
  local m = manifest({ c2, c1 },
    { prof("p", { "dep_second", "dep_first" }) },
    { ["json.lua"] = fnv_hex(BASE_BYTES["json.lua"]) })
  local ad = fake_adapter({ commits = {
    [c1.candidate_sha] = { paths = { ["json.lua"] = s1 } },
    [c2.candidate_sha] = { paths = { ["json.lua"] = s2 } },
  }, ancestors = { [c1.candidate_sha .. ">" .. c2.candidate_sha] = true } })
  local res, tree_dir = run(m, ad, "p", "f2", base_dir)
  ok(res.tree["json.lua"] == fnv_hex(s2),
    "F2 later dependent leaf owns the overlapping path")
  ok(read_file(tree_dir .. "/json.lua") == s2, "F2 written bytes are the winner's")
end

