fn currentness_lens(extra: &'static [&'static str]) -> LensSpec {
    LensSpec {
        name: "coherent_subject_currentness",
        applicable: true,
        reason: "the review binds exactly one source/document/root/configuration subject at one head",
        questions: extra,
    }
}

