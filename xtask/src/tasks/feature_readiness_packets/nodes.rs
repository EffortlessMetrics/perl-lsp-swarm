//!
//! Every node's stable semantics are anchored to its owning issue; this file
//! compiles those anchors into typed rows (role, domain, policy, artifacts,
//! falsifiers, lenses, old-path exits). It encodes no readiness evaluation
//! and no observational state: observational planes degrade honestly to
//! `unavailable` until their owning trains land (#11280/#11281/#11283).

